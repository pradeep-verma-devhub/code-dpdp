import os
import subprocess
import time
from pathlib import Path
from typing import List, Dict, Any
from ..core.models import Finding

class PatchGenerator:

    @classmethod
    def generate_patches(
        cls,
        findings: List[Finding],
        output_dir: str,
        target_path: str,
        apply: bool = False
    ) -> Dict[str, Any]:
        out_path = Path(output_dir).resolve()
        out_path.mkdir(parents=True, exist_ok=True)

        patchable_findings = [f for f in findings if f.patch_available and f.patch_unified_diff]
        patch_files: List[str] = []

        for f in patchable_findings:
            patch_name = f"{f.rule_id}_{f.id}.patch".replace("/", "_")
            file_dest = out_path / patch_name
            with open(file_dest, "w", encoding="utf-8") as pf:
                pf.write(f.patch_unified_diff + "\n")
            patch_files.append(str(file_dest))

        master_patch = out_path / "all_remediations.patch"
        with open(master_patch, "w", encoding="utf-8") as mf:
            for f in patchable_findings:
                mf.write(f"# Fix for {f.rule_id}: {f.title} ({f.file}:{f.line})\n")
                mf.write(f.patch_unified_diff + "\n\n")

        pr_info = None
        if apply and patchable_findings:
            pr_info = cls._apply_patches(target_path, master_patch, patchable_findings)

        return {
            "patches_dir": str(out_path),
            "generated_count": len(patch_files),
            "patch_files": patch_files,
            "master_patch": str(master_patch),
            "applied": bool(apply and pr_info),
            "pr_info": pr_info,
        }

    @classmethod
    def _apply_patches(
        cls,
        target_path: str,
        master_patch: Path,
        findings: List[Finding]
    ) -> Dict[str, Any]:
        target = Path(target_path).resolve()
        timestamp = int(time.time())
        branch_name = f"dpdp-remediation-{timestamp}"

        try:
            subprocess.run(["git", "checkout", "-b", branch_name], cwd=str(target), capture_output=True, text=True, check=True)
            apply_res = subprocess.run(
                ["git", "apply", "--ignore-whitespace", str(master_patch)],
                cwd=str(target),
                capture_output=True,
                text=True
            )
            applied_success = (apply_res.returncode == 0)
        except Exception:
            applied_success = False

        pr_md_path = target / "PR_REMEDIATION.md"
        pr_content = cls._generate_pr_markdown(branch_name, findings)
        with open(pr_md_path, "w", encoding="utf-8") as f:
            f.write(pr_content)

        return {
            "branch": branch_name,
            "applied_cleanly": applied_success,
            "pr_summary_file": str(pr_md_path),
        }

    @classmethod
    def _generate_pr_markdown(cls, branch: str, findings: List[Finding]) -> str:
        lines = [
            f"# PR: Automated DPDP Act 2023 & DPDP Rules 2025 Compliance Remediation",
            f"",
            f"**Branch**: `{branch}`  ",
            f"**Generated by**: `DPDP-Audit` Compliance Scanner  ",
            f"**Remediated Findings**: {len(findings)} automated security & privacy fixes  ",
            f"",
            f"## Summary of Statutory Protections Applied",
            f"This Pull Request automatically resolves privacy violations and security gaps detected under India's Digital Personal Data Protection Act 2023 and DPDP Rules 2025.",
            f"",
            f"| Finding ID | Rule | DPDP Provision | Severity | Target File |",
            f"| :--- | :--- | :--- | :--- | :--- |",
        ]
        for f in findings:
            prov = f.dpdp_ref.get("sectionOrRule", "DPDP Act 2023")
            lines.append(f"| `{f.id}` | {f.title} | **{prov}** | `{f.severity.upper()}` | `{f.file}:{f.line}` |")

        lines.extend([
            f"",
            f"## Verification & Testing",
            f"1. Run existing unit and integration test suites: `npm test`",
            f"2. Re-run DPDP-Audit scanner to verify 100% remediation: `dpdp-audit scan .`",
            f"",
            f"> *Note: Review each diff prior to merging into production branches.*",
        ])
        return "\n".join(lines)
